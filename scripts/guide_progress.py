"""Rewrite docs/GUIDE_PROGRESS.md: handwritten guide progress, remaining groups in priority order, next group.

Priority: kid-safe groups by youngest kid-safe age band (5-7, 8-10, 11-13, teen+), then by number of kid-safe
entries; then groups that only have ask-a-grown-up entries by size.  Usage: python scripts/guide_progress.py
"""
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import guide_helpers as gh  # noqa: E402

DATA = ROOT / "src" / "data"


def load():
    es = [e for n in ("learn", "build", "kids") for e in json.loads((DATA / f"{n}.json").read_text(encoding="utf-8"))]
    return [e for e in es if e["safety"] != "adult-only"]


def ordered_groups(vis):
    g = collections.defaultdict(list)
    for e in vis:
        g[gh.group_of(e)].append(e)

    def key(item):
        k, l = item
        ks = [e for e in l if e["safety"] == "kid-safe"]
        if ks:
            return (0, min(gh.AGES.index(e["age_group"]) for e in ks), -len(ks), k)
        return (1, 0, -len(l), k)
    return sorted(g.items(), key=key)


def main():
    vis = load()
    guides = json.loads((DATA / "guides.json").read_text(encoding="utf-8"))
    lessons = json.loads((DATA / "lessons.json").read_text(encoding="utf-8"))
    order = ordered_groups(vis)
    done = [k for k, _ in order if k in guides["groups"]]
    todo = [k for k, _ in order if k not in guides["groups"]]
    covered = collections.Counter()
    total = collections.Counter()
    for e in vis:
        band = e["age_group"] if e["safety"] == "kid-safe" else "ask-a-grown-up"
        total[band] += 1
        covered[band] += gh.group_of(e) in guides["groups"]
    lines = [
        "# Guide and lesson progress (resume file; regenerated by `python scripts/guide_progress.py`)",
        "",
        "Branch `guides-lessons`. Fully automatic run. To resume: write the next group's guide in a new",
        "`scripts/guide_content/batchNN.py` (same format as `batch01.py`), run `python scripts/build_guides.py`,",
        "the tests, `python scripts/guide_progress.py`, then commit.",
        "",
        "## Status",
        f"- Phase A (foundation): DONE. Phase B (lessons): DONE ({len(lessons)} lessons).",
        f"- Phase C (handwritten guides): {len(done)} of {len(order)} groups done; {len(guides['fallback'])} topic fallbacks always cover the rest.",
        f"- Entries with a handwritten guide: {sum(covered.values())} of {sum(total.values())} visible.",
        "",
        "| Band | Entries with handwritten guide | Visible entries |", "|---|---|---|",
    ]
    for band in gh.AGES + ["ask-a-grown-up"]:
        lines.append(f"| {band if band == 'ask-a-grown-up' else 'kid-safe ' + band} | {covered[band]} | {total[band]} |")
    lines += ["", "## NEXT", f"`{todo[0]}`" if todo else "Phase D (wrap-up) if not done yet; all groups have guides.", "",
              "## Remaining groups in priority order", ""]
    lines += [f"{i}. `{k}`" for i, k in enumerate(todo, 1)]
    lines += ["", "## Done groups", ""] + [f"- `{k}`" for k in done]
    (ROOT / "docs" / "GUIDE_PROGRESS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(done)}/{len(order)} groups; next: {todo[0] if todo else 'none'}")


if __name__ == "__main__":
    main()
