"""Add `reuse` to every entry (deterministic; run after categorize.py, before guides/lessons).

  reuse = "open-content"  the CONTENT license is verified to allow reuse/adaptation.
                          Today only CS Unplugged (CC BY-SA 4.0, LICENCE-CONTENT, see docs/SOURCES.md).
                          `reuse_license` then names the license.
  reuse = "link-only"     everything else. We may only describe it and link out.

A GitHub code license alone never counts. Unclear candidates are logged in docs/REUSE_CANDIDATES.md.
Ids and ordering are left unchanged.  Usage: python scripts/mark_reuse.py
"""
import collections
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src" / "data"

# source repo URL -> license that is verified (docs/SOURCES.md) to cover the CONTENT
VERIFIED_CONTENT = {"https://github.com/uccser/cs-unplugged": "CC-BY-SA-4.0"}

# Hosts we looked at as possible reuse candidates, and why we did NOT mark them.
CANDIDATES = {
    "developer.mozilla.org": "MDN text is CC BY-SA 2.5 per the site; not verified from a source repo here, and code samples differ (CC0).",
    "en.wikipedia.org": "Wikipedia text is CC BY-SA, but each article has its own history and media licenses; not verified per page.",
    "www.freecodecamp.org": "freeCodeCamp's repo licenses its curriculum CC BY-SA 4.0, but we did not verify it per page.",
    "github.com": "Repository licenses vary and a code license (MIT etc.) does not cover the written lesson content.",
    "www.khanacademy.org": "Khan Academy content is CC BY-NC-SA (non-commercial); not safe to adapt.",
    "docs.python.org": "Python docs use the PSF license; reuse terms need a per-page check.",
    "www.youtube.com": "Videos are copyrighted unless marked CC BY; never reusable by default.",
}


def main():
    counts, hosts = collections.Counter(), collections.Counter()
    for name in ("learn", "build", "kids"):
        path = DATA / f"{name}.json"
        entries = json.loads(path.read_text(encoding="utf-8"))
        for e in entries:
            lic = VERIFIED_CONTENT.get(e["source"])
            if lic and e.get("license") == lic:
                e["reuse"], e["reuse_license"] = "open-content", lic
            else:
                e["reuse"] = "link-only"
                e.pop("reuse_license", None)
            counts[e["reuse"]] += 1
            if e["safety"] != "adult-only":
                hosts[urlparse(e["url"]).netloc.lower()] += 1
        path.write_text(json.dumps(entries, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = ["# Reuse candidates (not marked open-content)\n",
             "Generated by `scripts/mark_reuse.py`. Only CS Unplugged is `open-content`: its repo states CC BY-SA 4.0 for the lesson CONTENT (`LICENCE-CONTENT`). Everything below is `link-only` until someone verifies the content license and records it in `docs/SOURCES.md`.\n",
             "| Host | Visible entries | Why it is NOT marked open-content |", "|---|---|---|"]
    for host, why in CANDIDATES.items():
        lines.append(f"| {host} | {hosts.get(host, 0)} | {why} |")
    lines += ["", "Any other host: link-only by default (we know nothing about its content license).", ""]
    (ROOT / "docs" / "REUSE_CANDIDATES.md").write_text("\n".join(lines), encoding="utf-8")
    print(dict(counts))


if __name__ == "__main__":
    main()
